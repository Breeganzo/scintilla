"""Load and validate the golden set.

The golden set is the only thing in this project that cannot be regenerated by
running code. Every label was assigned by a person reading a title and an
abstract, and if the file is corrupted the corruption is silent: a truncated
identifier does not raise, it simply never matches, and the affected query
reports zero recall for every retriever equally. That failure is invisible in
an ablation table - all three modes look uniformly bad on one query, which is
indistinguishable from a genuinely hard query.

So the file is validated on load, hard, and the loader refuses to return a set
it does not fully trust. The alternative is discovering on the morning of a
deadline that a metric has been quietly wrong for a week.
"""

from __future__ import annotations

import re
from dataclasses import dataclass
from pathlib import Path
from typing import Any

import yaml

GOLDEN_SET_DIR = Path(__file__).resolve().parent / "golden_set"
DEFAULT_VERSION = 1

QUERY_CLASSES = (
    "exact_term",
    "paraphrase",
    "conceptual",
    "multi_hop",
    "unanswerable",
)

#: Every class must contain exactly this many queries. A class that quietly
#: shrinks would make per-class averages incomparable between versions.
QUERIES_PER_CLASS = 10

#: arXiv identifiers in the modern scheme: four digits, a dot, four or five.
ARXIV_ID = re.compile(r"^\d{4}\.\d{4,5}$")


class GoldenSetError(Exception):
    """The golden set file is malformed. Never raised at runtime in production."""


@dataclass(frozen=True)
class GoldenQuery:
    id: str
    query: str
    query_class: str
    relevant_ids: tuple[str, ...]
    notes: str = ""

    @property
    def is_unanswerable(self) -> bool:
        return self.query_class == "unanswerable"


@dataclass(frozen=True)
class GoldenSet:
    version: int
    corpus: dict[str, Any]
    pool: dict[str, Any]
    queries: tuple[GoldenQuery, ...]

    def __len__(self) -> int:
        return len(self.queries)

    def __iter__(self):
        return iter(self.queries)

    def by_class(self, query_class: str) -> tuple[GoldenQuery, ...]:
        return tuple(q for q in self.queries if q.query_class == query_class)

    @property
    def relevant_ids(self) -> frozenset[str]:
        """Every paper referenced anywhere in the set, for existence checking."""
        return frozenset(pid for q in self.queries for pid in q.relevant_ids)


def golden_set_path(version: int = DEFAULT_VERSION) -> Path:
    return GOLDEN_SET_DIR / f"v{version}.yaml"


def load_golden_set(version: int = DEFAULT_VERSION, path: Path | None = None) -> GoldenSet:
    """Read, validate and return a golden set. Raises GoldenSetError if unusable."""
    source = path if path is not None else golden_set_path(version)
    if not source.exists():
        raise GoldenSetError(f"no golden set at {source}")

    raw = yaml.safe_load(source.read_text(encoding="utf-8"))
    if not isinstance(raw, dict):
        raise GoldenSetError(f"{source} does not contain a mapping")

    queries = tuple(_parse_query(entry, index) for index, entry in enumerate(_entries(raw, source)))
    _validate(queries, source)

    return GoldenSet(
        version=int(raw.get("version", version)),
        corpus=dict(raw.get("corpus") or {}),
        pool=dict(raw.get("pool") or {}),
        queries=queries,
    )


def _entries(raw: dict[str, Any], source: Path) -> list[Any]:
    entries = raw.get("queries")
    if not isinstance(entries, list) or not entries:
        raise GoldenSetError(f"{source} has no queries")
    return entries


def _parse_query(entry: Any, index: int) -> GoldenQuery:
    if not isinstance(entry, dict):
        raise GoldenSetError(f"query {index} is not a mapping")

    missing = {"id", "class", "query", "relevant_ids"} - set(entry)
    if missing:
        raise GoldenSetError(f"query {index} is missing {sorted(missing)}")

    ids = entry["relevant_ids"] or []
    if not isinstance(ids, list):
        raise GoldenSetError(f"query {entry['id']} has a non-list relevant_ids")

    for pid in ids:
        # A bare 2607.07800 in YAML is the float 2607.078. It parses, it looks
        # right in a diff, and it matches nothing. Catch it at the type level.
        if not isinstance(pid, str):
            raise GoldenSetError(
                f"query {entry['id']} has a non-string id {pid!r} "
                f"({type(pid).__name__}) - arXiv ids must be quoted in YAML"
            )
        if not ARXIV_ID.match(pid):
            raise GoldenSetError(f"query {entry['id']} has a malformed arXiv id {pid!r}")

    return GoldenQuery(
        id=str(entry["id"]),
        query=str(entry["query"]).strip(),
        query_class=str(entry["class"]),
        relevant_ids=tuple(ids),
        notes=str(entry.get("notes", "")).strip(),
    )


def _validate(queries: tuple[GoldenQuery, ...], source: Path) -> None:
    seen: set[str] = set()
    for query in queries:
        if query.id in seen:
            raise GoldenSetError(f"duplicate query id {query.id!r} in {source}")
        seen.add(query.id)

        if query.query_class not in QUERY_CLASSES:
            raise GoldenSetError(f"query {query.id} has unknown class {query.query_class!r}")

        if not query.query:
            raise GoldenSetError(f"query {query.id} has an empty query string")

        if len(set(query.relevant_ids)) != len(query.relevant_ids):
            raise GoldenSetError(f"query {query.id} lists the same paper twice")

        # The whole point of the unanswerable class is that the right answer is
        # nothing. A stray label here would turn a test of abstention into a
        # test of retrieval, and nobody would notice.
        if query.is_unanswerable and query.relevant_ids:
            raise GoldenSetError(f"unanswerable query {query.id} has relevant ids")
        if not query.is_unanswerable and not query.relevant_ids:
            raise GoldenSetError(f"answerable query {query.id} has no relevant ids")

    for query_class in QUERY_CLASSES:
        count = sum(1 for q in queries if q.query_class == query_class)
        if count != QUERIES_PER_CLASS:
            raise GoldenSetError(
                f"{source} has {count} {query_class} queries, expected {QUERIES_PER_CLASS}"
            )
